  T.chatNode = function (contactId, data) {
    var list = T.CHAT_NODES[contactId] || [];
    var day = (data && data.day) || 1;
    if (!T.contactUnlocked(contactId, data)) return null;
    var done = (data && data.chatDone) || {};
    for (var i = 0; i < list.length; i++) {
      if (list[i].day <= day && !done[list[i].id]) return list[i];
    }
    // переписка постоянных покупателей — в cast.js
    if (PVZ.cast && PVZ.cast.chatNode) return PVZ.cast.chatNode(contactId, data);
    return null;
  };

  T.idleNode = function (contactId, data) {
    var list = T.IDLE_CHATS[contactId] || [];
    if (!list.length) {
      if (PVZ.cast && PVZ.cast.idleChat) return PVZ.cast.idleChat(contactId, data);
      return null;
    }
    var day = (data && data.day) || 1;
    var idleDone = (data && data.chatIdleDone) || {};
    if (idleDone[contactId] === day) return null;
    var idx = Math.floor(U.hash(day * 11.3 + contactId.length) * list.length) % list.length;
    var src = list[idx];
    return {
      id: 'idle_' + contactId + '_' + day,
      idle: true,
      day: day,
      msgs: src.msgs,
      replies: src.replies
    };
  };

  /* Текущий узел переписки: сначала сюжет, потом бытовая болтовня */
  T.currentNode = function (contactId, data) {
    return T.chatNode(contactId, data) || T.idleNode(contactId, data);
  };

  /* Показываем непрочитанное: сюжетный узел, ещё не отмеченный как открытый */
  T.pendingNode = function (contactId, data) {
    var node = T.chatNode(contactId, data);
    if (!node) return null;
    var posted = (data && data.chatPosted) || {};
    return posted[node.id] ? null : node;
  };

  T.pendingCount = function (data) {
    var n = 0;
    T.contacts().forEach(function (c) { if (T.pendingNode(c.id, data)) n++; });
    return n;
  };

  /* Первое открытие переписки: досыпаем новые сообщения узла в чат */
  T.ensureThread = function (contactId) {
    var d = PVZ.state.data;
    if (!d) return null;
    if (!T.contactUnlocked(contactId, d)) return null;
    if (!d.chatPosted || typeof d.chatPosted !== 'object') d.chatPosted = {};
    var node = T.currentNode(contactId, d);
    if (!node) return null;
    if (!d.chatPosted[node.id]) {
      d.chatPosted[node.id] = 1;
      node.msgs.forEach(function (text) { PVZ.state.chatAdd(contactId, text, contactId); });
      PVZ.state.save();
    }
    return node;
  };

  T.applyChatFx = function (fx) {
    if (!fx) return;
    var S = PVZ.state;
    if (fx.money) S.addMoney(fx.money);
    if (fx.rating) S.addRating(fx.rating);
    if (fx.mafia) {
      if (fx.mafia.trust) S.mafiaAdd('trust', fx.mafia.trust);
      if (fx.mafia.dirt) S.mafiaAdd('dirt', fx.mafia.dirt);
      if (fx.mafia.proof) S.mafiaAdd('proof', fx.mafia.proof);
    }
  };

  /* Ответ в переписке. Возвращает выбранный вариант либо null. */
  T.answerChat = function (contactId, index) {
    var d = PVZ.state.data;
    if (!d) return null;
    var node = T.currentNode(contactId, d);
    if (!node || !node.replies || !node.replies[index]) return null;
    if (!d.chatPosted || typeof d.chatPosted !== 'object') d.chatPosted = {};
    if (!d.chatPosted[node.id]) {
      d.chatPosted[node.id] = 1;
      node.msgs.forEach(function (text) { PVZ.state.chatAdd(contactId, text, contactId); });
    }
    var r = node.replies[index];
    PVZ.state.chatAdd('me', r.t, contactId);
    (r.reply || []).forEach(function (text) { PVZ.state.chatAdd(contactId, text, contactId); });
    if (node.idle) {
      if (!d.chatIdleDone || typeof d.chatIdleDone !== 'object') d.chatIdleDone = {};
      d.chatIdleDone[contactId] = d.day || 1;
    } else {
      if (!d.chatDone || typeof d.chatDone !== 'object') d.chatDone = {};
      d.chatDone[node.id] = 1;
    }
    T.applyChatFx(r.fx);
    T.save();
    return r;
  };

  T.save = function () { if (PVZ.state && PVZ.state.save) PVZ.state.save(); };

  /* Узел можно ответить только один раз: при повторном показе вариантов нет */
  T.repliesFor = function (contactId, data) {
    var node = T.currentNode(contactId, data);
    if (!node) return [];
    if (node.idle) {
      var idleDone = (data && data.chatIdleDone) || {};
      return idleDone[contactId] === ((data && data.day) || 1) ? [] : (node.replies || []);
    }
    var done = (data && data.chatDone) || {};
    return done[node.id] ? [] : (node.replies || []);
  };
