  /* По очереди: день 1 — Семён, день 2 — Лиза, день 3 — Вера, и заново */
  T.npcForDay = function (day) {
    var n = T.NPCS.length;
    return T.NPCS[(Math.max(1, day || 1) - 1) % n];
  };

  T.npcSeen = function (data, npcId) {
    if (!data) return [];
    if (!data.npcSeen || typeof data.npcSeen !== 'object') data.npcSeen = {};
    if (!Array.isArray(data.npcSeen[npcId])) data.npcSeen[npcId] = [];
    return data.npcSeen[npcId];
  };

  /* Следующий непройденный визит: берём самый ранний по дню визит */
  T.nextBeat = function (npc, data) {
    if (!npc) return null;
    var seen = T.npcSeen(data, npc.id);
    var day = (data && data.day) || 1;
    var best = null;
    for (var i = 0; i < npc.beats.length; i++) {
      var b = npc.beats[i];
      if (seen.indexOf(b.id) >= 0) continue;
      if (b.day > day) continue;
      if (!best || b.day < best.day) best = b;
    }
    return best;
  };

  T.markBeat = function (npcId, beatId) {
    var d = PVZ.state.data;
    if (!d) return;
    var seen = T.npcSeen(d, npcId);
    if (seen.indexOf(beatId) < 0) seen.push(beatId);
    T.save();
  };

  /* Кто заходит сегодня: первый по кругу, у кого есть непройденный визит.
     Пропущенный визит не теряется — он просто ждёт следующего дня. */
  T.dueNpc = function (day, data) {
    var n = T.NPCS.length;
    for (var i = 0; i < n; i++) {
      var npc = T.NPCS[((Math.max(1, day || 1) - 1) + i) % n];
      var beat = T.nextBeat(npc, data);
      if (beat) return { npc: npc, beat: beat };
    }
    return null;
  };

