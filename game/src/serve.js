  S.colorFor = function (name, kind) {
    var key = PVZ.art && PVZ.art.itemKindOf ? PVZ.art.itemKindOf(name, kind || 'other') : null;
    if (key && KEY_COLORS[key]) return KEY_COLORS[key];
    var s = String(name || '');
    var h = 0;
    for (var i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
    return ITEM_COLORS[h % ITEM_COLORS.length];
  };

  /* Выбрать микросцену под заказ. Одна выдача — одна сценка. */
  var recent = [];
  S.momentFor = function (c, order) {
    if (!order) return null;
    var pool;
    if (order.kind === 'clothes') {
      pool = S.MOMENTS.filter(function (m) { return m.id === 'clothes_here'; });
    } else {
      var key = S.itemKey(order);
      pool = S.MOMENTS.filter(function (m) {
        if (m.id === 'generic_check') return false;
        if (m.key && m.key === key && (!m.names || m.names.test(order.item))) return true;
        return false;
      });
    }
    if (!pool.length) pool = S.MOMENTS.filter(function (m) { return m.id === 'generic_check'; });
    // подряд одна и та же сценка не выпадает
    var fresh = pool.filter(function (m) { return recent.indexOf(m.id) < 0; });
    var m = U.pick(fresh.length ? fresh : pool);
    recent.push(m.id);
    while (recent.length > 5) recent.shift();
    return {
      id: m.id,
      scene: m.scene || 'item',
      title: m.title || 'Выдача',
      text: String(m.text || '').replace(/\{item\}/g, order.item),
      choices: (m.choices || []).map(function (ch) {
        return {
          label: String(ch.label || '').replace(/\{item\}/g, order.item),
          hint: ch.hint || '',
          fx: ch.fx || null,
          reply: String(ch.reply || '').replace(/\{item\}/g, order.item),
          tip: ch.tip || 0,
          queue: ch.queue || 0
        };
      })
    };
  };

