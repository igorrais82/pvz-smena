  S.specialById = function (id) {
    for (var i = 0; i < S.SPECIALS.length; i++) if (S.SPECIALS[i].id === id) return S.SPECIALS[i];
    return null;
  };

  S.ensure = function (data) {
    data = data || (PVZ.state && PVZ.state.data);
    if (!data) return null;
    if (!data.serve || typeof data.serve !== 'object') data.serve = { specials: {}, moments: 0, guests: 0 };
    if (!data.serve.specials || typeof data.serve.specials !== 'object') data.serve.specials = {};
    if (typeof data.serve.moments !== 'number') data.serve.moments = 0;
    if (typeof data.serve.guests !== 'number') data.serve.guests = 0;
    return data.serve;
  };

  S.seen = function (id, data) {
    var s = S.ensure(data);
    return s && s.specials[id] != null ? s.specials[id] : null;
  };

  S.markSeen = function (id, day, data) {
    var s = S.ensure(data);
    if (!s) return;
    s.specials[id] = day || 1;
    s.guests = (s.guests || 0) + 1;
    if (PVZ.state && PVZ.state.save) PVZ.state.save();
  };

  /* Кто приходит в этот день. В бесконечном режиме особые гости идут по
     кругу, но не чаще раза в 12 смен. */
  S.specialForDay = function (day, data) {
    var story = !(PVZ.state && PVZ.state.endless && PVZ.state.endless());
    var def = null;
    if (story) {
      for (var i = 0; i < S.SPECIALS.length; i++) {
        if (S.SPECIALS[i].day === day) { def = S.SPECIALS[i]; break; }
      }
    } else if (day >= 2) {
      // в бесконечном режиме гости идут по кругу, начиная со второй смены
      def = S.SPECIALS[(day - 2) % S.SPECIALS.length];
    }
    if (!def) return null;
    var seenDay = S.seen(def.id, data);
    if (seenDay != null) {
      if (story) return null;
      if (day - seenDay < 12) return null;
    }
    return def;
  };

  S.dueSpecial = function (day, clock, data) {
    var def = S.specialForDay(day, data);
    if (!def) return null;
    if (clock < def.at) return null;
    return def;
  };

  S.warning = function (day, data) {
    var def = S.specialForDay(day, data);
    return def ? def.warning || '' : '';
  };

