  C.touch = function (data) {
    var d = data || (PVZ.state && PVZ.state.data);
    if (!d) return null;
    if (!d.cast || typeof d.cast !== 'object') d.cast = {};
    var c = d.cast;
    if (!c.rel || typeof c.rel !== 'object') c.rel = {};
    if (!c.beats || typeof c.beats !== 'object') c.beats = {};
    if (!c.met || typeof c.met !== 'object') c.met = {};
    if (!c.refs || typeof c.refs !== 'object') c.refs = {};
    if (!c.lastDay || typeof c.lastDay !== 'object') c.lastDay = {};
    if (!Array.isArray(c.nums)) c.nums = [];
    if (typeof c.totalRefs !== 'number') c.totalRefs = 0;
    var day = d.day || 1;
    if (!c.daySeen || typeof c.daySeen !== 'object' || c.daySeen.day !== day) {
      c.daySeen = { day: day, ids: {} };
    }
    if (!c.daySeen.ids || typeof c.daySeen.ids !== 'object') c.daySeen.ids = {};
    return c;
  };

  C.save = function () {
    if (PVZ.state && PVZ.state.save) PVZ.state.save();
  };

  C.byId = function (id) {
    for (var i = 0; i < C.CHARS.length; i++) if (C.CHARS[i].id === id) return C.CHARS[i];
    return null;
  };

  /* У каждого свой характер — он же задаёт терпение и манеру говорить */
  C.MOOD = {
    marina: 'chatty', kirill: 'hurry', olga: 'elder', matvey: 'elder',
    timur: 'calm', lyuda: 'calm', alina: 'chatty', arkady: 'calm',
    gosha: 'grumpy', klara: 'grumpy', sergey: 'calm', dana: 'grumpy'
  };
  C.moodOf = function (ch) {
    if (!ch) return null;
    return ch.mood || C.MOOD[ch.id] || (ch.align === 'bad' ? 'grumpy' : 'calm');
  };

  C.byContact = function (cid) {
    if (!cid) return null;
    var m = /^c_(.+)$/.exec(String(cid));
    return m ? C.byId(m[1]) : null;
  };

  C.contactId = function (id) { return 'c_' + id; };

  C.rel = function (id, data) {
    var st = C.touch(data);
    return st ? (st.rel[id] || 0) : 0;
  };

  C.addRel = function (id, delta, data) {
    var st = C.touch(data);
    if (!st || !delta) return 0;
    st.rel[id] = U.clamp((st.rel[id] || 0) + delta, -5, 8);
    return st.rel[id];
  };

  C.beatsDone = function (id, data) {
    var st = C.touch(data);
    return st && Array.isArray(st.beats[id]) ? st.beats[id] : [];
  };

  C.markBeat = function (id, beatId, data) {
    var st = C.touch(data);
    if (!st) return;
    if (!Array.isArray(st.beats[id])) st.beats[id] = [];
    if (st.beats[id].indexOf(beatId) < 0) st.beats[id].push(beatId);
    C.save();
  };

  C.beat = function (char, beatId) {
    if (!char) return null;
    for (var i = 0; i < char.beats.length; i++) if (char.beats[i].id === beatId) return char.beats[i];
    return null;
  };

  /* Следующий личный визит: первый непройденный бит, до которого дорос день */
  C.nextBeat = function (char, data) {
    if (!char) return null;
    var d = data || (PVZ.state && PVZ.state.data) || {};
    var done = C.beatsDone(char.id, d);
    var day = d.day || 1;
    for (var i = 0; i < char.beats.length; i++) {
      var b = char.beats[i];
      if (done.indexOf(b.id) >= 0) continue;
      if ((b.minDay || 1) > day) continue;
      return b;
    }
    return null;
  };

  C.hasNumber = function (id, data) {
    var st = C.touch(data);
    return !!(st && st.nums.indexOf(id) >= 0);
  };

  C.markMet = function (id, day) {
    var st = C.touch();
    if (!st) return;
    if (st.met[id] == null) st.met[id] = day || (PVZ.state.data && PVZ.state.data.day) || 1;
    C.save();
  };

  C.giveNumber = function (id) {
    var st = C.touch();
    var ch = C.byId(id);
    if (!st || !ch || st.nums.indexOf(id) >= 0) return false;
    st.nums.push(id);
    if (PVZ.talks && PVZ.talks.unlockContact) PVZ.talks.unlockContact(C.contactId(id));
    C.save();
    return true;
  };

  C.contacts = function () {
    var st = C.touch();
    if (!st) return [];
    return st.nums.map(function (id) {
      var ch = C.byId(id);
      if (!ch) return null;
      return {
        id: C.contactId(id),
        name: ch.name + ' ' + (ch.last || ''),
        note: ch.role,
        color: ch.color || '#8a8a92',
        initial: (ch.name || '?').charAt(0),
        base: false
      };
    }).filter(Boolean);
  };

  /* ---- переписка ---- */
  C.chatNode = function (cid, data) {
    var ch = C.byContact(cid);
    if (!ch || !ch.chats || !ch.chats.length) return null;
    if (PVZ.talks && PVZ.talks.contactUnlocked && !PVZ.talks.contactUnlocked(cid, data)) return null;
    var day = (data && data.day) || 1;
    var done = (data && data.chatDone) || {};
    for (var i = 0; i < ch.chats.length; i++) {
      var n = ch.chats[i];
      if ((n.day || 1) <= day && !done[n.id]) return n;
    }
    return null;
  };

  C.idleChat = function (cid, data) {
    var ch = C.byContact(cid);
    if (!ch || !ch.idleChats || !ch.idleChats.length) return null;
    var day = (data && data.day) || 1;
    var done = (data && data.chatIdleDone) || {};
    if (done[cid] === day) return null;
    var idx = Math.floor(U.hash(day * 7.3 + cid.length) * ch.idleChats.length) % ch.idleChats.length;
    var src = ch.idleChats[idx];
    return { id: 'cast_idle_' + cid + '_' + day, idle: true, day: day, msgs: src.msgs, replies: src.replies };
  };

  /* ======================================================================
     ВЫБОР ПОКУПАТЕЛЯ
     ====================================================================== */
  C.pick = function (day, data, opts) {
    opts = opts || {};
    var st = C.touch(data);
    var d = data || (PVZ.state && PVZ.state.data) || {};
    day = day || d.day || 1;
    var pool = C.CHARS.filter(function (ch) {
      return (ch.fromDay || 1) <= day;
    });
    if (opts.exclude && opts.exclude.length) {
      var ex = opts.exclude;
      var p2 = pool.filter(function (ch) { return ex.indexOf(ch.id) < 0; });
      if (p2.length) pool = p2;
    }
    if (!pool.length) pool = C.CHARS.slice();
    // сегодня ещё не заходил — так в зале разные лица
    var fresh = pool.filter(function (ch) { return !st || !st.daySeen.ids[ch.id]; });
    if (fresh.length >= 2) pool = fresh;
    // приоритет тем, у кого есть новая личная история
    var withBeat = pool.filter(function (ch) { return !!C.nextBeat(ch, d); });
    var list = withBeat.length ? withBeat : pool;
    // плохие и хорошие приходят примерно поровну, с перекосом в хороших
    var weights = list.map(function (ch) {
      var w = ch.align === 'bad' ? 0.7 : ch.align === 'good' ? 1.2 : 1;
      if (C.nextBeat(ch, d)) w += 0.5;
      if (!C.hasNumber(ch.id, d)) w += 0.2;
      return w;
    });
    var sum = 0;
    weights.forEach(function (w) { sum += w; });
    var r = Math.random() * sum;
    var pick = list[list.length - 1];
    for (var i = 0; i < list.length; i++) {
      r -= weights[i];
      if (r <= 0) { pick = list[i]; break; }
    }
    if (st) {
      st.lastPickNew = st.met[pick.id] == null;
      st.daySeen.ids[pick.id] = (st.daySeen.ids[pick.id] || 0) + 1;
      if (st.met[pick.id] == null) st.met[pick.id] = day;
      st.lastDay[pick.id] = day;
      C.save();
    }
    return pick;
  };

  /* Надеть на покупателя лицо и характер персонажа */
  C.dress = function (c, ch) {
    if (!c || !ch) return c;
    c.castId = ch.id;
    c.castAlign = ch.align || 'neutral';
    c.castRole = ch.role;
    c.name = ch.name;
    c.last = ch.last || '';
    if (ch.female != null) c.female = ch.female;
    var look = ch.look || {};
    Object.keys(look).forEach(function (k) {
      if (look[k] !== undefined) c[k] = look[k];
    });
    return c;
  };

  C.greeting = function (ch, c) {
    if (!ch) return '';
    if (c && c.referredBy) return 'Здравствуйте! Мне вас посоветовали: ' + c.referredBy + '. Говорят, тут по-человечески.';
    if (c && c.castNew) {
      return U.pick([
        'Здравствуйте! Мне бы получить заказ.',
        'Добрый день! Я к вам.',
        'Здравствуйте. У меня посылка и немного времени.'
      ]);
    }
    return U.pick(ch.greet || ['Здравствуйте!']);
  };

  /* ======================================================================
     РЕКОМЕНДАЦИИ
     ====================================================================== */
  C.refs = function (id, data) {
    var st = C.touch(data);
    return st ? (st.refs[id] || 0) : 0;
  };

  C.totalRefs = function (data) {
    var st = C.touch(data);
    return st ? st.totalRefs || 0 : 0;
  };

  C.canRefer = function (ch, data) {
    if (!ch) return false;
    var max = ch.maxRefs || 2;
    return C.refs(ch.id, data) < max;
  };

  /* Кого персонаж приведёт: нового персонажа, которого ещё не встречали */
  C.referralTarget = function (ch, data, day) {
    var st = C.touch(data);
    if (!st) return null;
    var pool = C.CHARS.filter(function (x) {
      return x.id !== ch.id && (x.fromDay || 1) <= day;
    });
    var unseen = pool.filter(function (x) { return !st.met[x.id]; });
    if (unseen.length) return U.pick(unseen);
    var rare = pool.filter(function (x) { return x.align !== 'bad'; });
    return U.pick(rare.length ? rare : pool);
  };

  C.makeReferral = function (ch, day) {
    var st = C.touch();
    if (!st || !ch || !C.canRefer(ch)) return null;
    var target = C.referralTarget(ch, null, day || (PVZ.state.data && PVZ.state.data.day) || 1);
    if (!target) return null;
    st.refs[ch.id] = (st.refs[ch.id] || 0) + 1;
    st.totalRefs = (st.totalRefs || 0) + 1;
    C.save();
    return { char: target, by: ch.name };
  };

  /* ======================================================================
     ОТНОШЕНИЯ: что сказать игроку после разговора
     ====================================================================== */
  C.relLabel = function (rel) {
    if (rel >= 5) return 'почти друг';
    if (rel >= 3) return 'приятель';
    if (rel >= 1) return 'знакомый';
    if (rel <= -2) return 'обижен';
    return 'нейтрально';
  };

  /* Награда за законченный личный разговор: номер, рекомендация, отзыв.
     Возвращает объект с сообщениями для сцены. */
  C.finishBeat = function (c, ch, beat, data) {
    var out = { number: false, referral: null, rel: C.rel(ch.id, data) };
    if (!c || !ch || !beat) return out;
    // номер дают после первой откровенной истории, а если отношения не сложились —
    // позже, когда человек уже точно вам доверяет
    var numRel = beat.number ? 1 : 2;
    if (out.rel >= numRel && !C.hasNumber(ch.id, data)) {
      if (C.giveNumber(ch.id)) out.number = true;
    }
    var canRef = (beat.ref !== false) && out.rel >= 2 && C.canRefer(ch, data);
    if (canRef && U.chance(0.75)) {
      out.referral = C.makeReferral(ch, (data && data.day) || 1);
    }
    return out;
  };
